"""Add the sha256 of every distribution file to requirements.lock.

requirements.lock lists each package once, as name==version. This script rewrites the file so
that every pin carries one --hash=sha256:... option for each file that PyPI lists for that
exact version (every wheel and the source archive), read from the PyPI JSON API at
https://pypi.org/pypi/<name>/<version>/json. Then

    python -m pip install --require-hashes -r requirements.lock

installs only those files, on any platform: pip refuses a file whose hash is not listed, and a
dependency that is not pinned with hashes.

To change a dependency, edit its pin in requirements.txt, install into a fresh virtual
environment, write the full pin set with

    python -m pip freeze --exclude-editable > requirements.lock

and run this script. It reads the pins from the file, hashed or not, and writes the file back
only after every lookup has succeeded.

Standard library only. The only host it contacts is pypi.org.
"""

import argparse
import json
import os
import re
import sys
import tempfile
import urllib.parse
import urllib.request
from pathlib import Path
from typing import NamedTuple

PYPI_JSON_URL = "https://pypi.org/pypi/{name}/{version}/json"
TIMEOUT_SECONDS = 30
DEFAULT_LOCK = Path(__file__).resolve().parents[1] / "requirements.lock"
HEADER = (
    "# Generated by scripts/lock_hashes.py. Do not edit by hand.\n"
    "# Install with: python -m pip install --require-hashes -r requirements.lock\n"
)
PIN = re.compile(
    r"(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[A-Za-z0-9][A-Za-z0-9.!+_-]*)"
    r"(?:\s+--hash=sha256:[0-9a-f]{64})*"
)
SHA256 = re.compile(r"[0-9a-f]{64}")


class LockError(Exception):
    """The lock cannot be read, or PyPI cannot supply its hashes."""


class Pin(NamedTuple):
    name: str
    version: str


def canonical(name: str) -> str:
    """The normal form of a package name (PEP 503)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_lock(text: str) -> list[Pin]:
    """The pins of a lock file, hashed or not. Anything but comments and exact pins is an error."""
    pins: list[Pin] = []
    seen: set[str] = set()
    for line in text.replace("\\\n", " ").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN.fullmatch(line)
        if not match:
            raise LockError(f"not an exact name==version pin: {line!r}")
        name = canonical(match["name"])
        if name in seen:
            raise LockError(f"{name} is pinned twice")
        seen.add(name)
        pins.append(Pin(match["name"], match["version"]))
    if not pins:
        raise LockError("no pins found")
    return pins


def sha256_digests(release: dict) -> list[str]:
    """The sha256 of every file of a PyPI JSON release document, sorted and without repeats."""
    files = release.get("urls") if isinstance(release, dict) else None
    if not isinstance(files, list) or not files:
        raise LockError("PyPI lists no files for this release")
    digests = set()
    for file in files:
        listed = file.get("digests") if isinstance(file, dict) else None
        digest = listed.get("sha256") if isinstance(listed, dict) else None
        if not isinstance(digest, str) or not SHA256.fullmatch(digest):
            filename = file.get("filename") if isinstance(file, dict) else None
            raise LockError(f"no usable sha256 for {filename!r}")
        digests.add(digest)
    return sorted(digests)


def fetch_release(name: str, version: str, urlopen=urllib.request.urlopen) -> dict:
    """The PyPI JSON document of one exact release; it must describe that release."""
    url = PYPI_JSON_URL.format(name=canonical(name), version=urllib.parse.quote(version))
    request = urllib.request.Request(
        url, headers={"Accept": "application/json", "User-Agent": "trioforge-lock-hashes"}
    )
    try:
        with urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            release = json.load(response)
    except (OSError, ValueError) as error:  # network and HTTP errors; unreadable JSON
        raise LockError(f"cannot read {url}: {error}") from error
    info = release.get("info") if isinstance(release, dict) else None
    if (
        not isinstance(info, dict)
        or canonical(str(info.get("name", ""))) != canonical(name)
        or info.get("version") != version
    ):
        raise LockError(f"{url} describes another release")
    return release


def render_lock(entries: list[tuple[Pin, list[str]]]) -> str:
    """The text of a hashed lock for ``entries``: pairs of a pin and its sorted digests."""
    blocks = []
    for pin, digests in sorted(entries, key=lambda entry: canonical(entry[0].name)):
        lines = [f"{pin.name}=={pin.version}"]
        lines += [f"    --hash=sha256:{digest}" for digest in digests]
        blocks.append(" \\\n".join(lines))
    return HEADER + "\n".join(blocks) + "\n"


def _read_lock(path: Path) -> str:
    """The text of the lock file. A UTF-8 byte order mark is dropped; other encodings are refused."""
    try:
        return path.read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as error:
        raise LockError(
            f"{path.name} is not UTF-8 text (Windows PowerShell 5 writes UTF-16 when it redirects "
            "with '>'; use PowerShell 7 or a POSIX shell)"
        ) from error


def _write_text(path: Path, text: str) -> None:
    """Replace ``path`` with ``text`` (LF line ends) in one step; a failure keeps the old file."""
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main(argv=None, fetch=fetch_release) -> int:
    parser = argparse.ArgumentParser(description="Add sha256 hashes from PyPI to a lock file.")
    parser.add_argument(
        "--lock",
        type=Path,
        default=DEFAULT_LOCK,
        help="the lock file to rewrite (default: requirements.lock at the repository root)",
    )
    args = parser.parse_args(argv)
    try:
        pins = parse_lock(_read_lock(args.lock))
        entries = []
        for pin in pins:
            try:
                entries.append((pin, sha256_digests(fetch(pin.name, pin.version))))
            except LockError as error:
                raise LockError(f"{pin.name}=={pin.version}: {error}") from error
        _write_text(args.lock, render_lock(entries))
    except (LockError, OSError) as error:
        print(f"lock_hashes: {error}", file=sys.stderr)
        return 1
    hashes = sum(len(digests) for _, digests in entries)
    print(f"{args.lock.name}: {len(entries)} packages, {hashes} hashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
